// TestLLMPlanner_ParsesPlanJSON Stub 返回合法计划 JSON，应解析为对应 Plan。
func TestLLMPlanner_ParsesPlanJSON(t *testing.T) {
	planJSON := `{"nodes":[
		{"id":"n1","type":"TOOL","name":"search","input":"go agent","dependsOn":[]},
		{"id":"n2","type":"LLM","name":"reason","input":"summarize","dependsOn":["n1"]}
	]}`
	stub := &llm.Stub{Responder: func(_ llm.Request) string { return planJSON }}
	p, err := (&LLMPlanner{LLM: stub}).Plan(context.Background(), &model.Run{ID: "run-1", Input: "research go agents"})
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if len(p.Nodes) != 2 {
		t.Fatalf("expected 2 nodes, got %d", len(p.Nodes))
	}
	if p.Nodes[0].Type != model.NodeTool || p.Nodes[0].Name != "search" {
		t.Errorf("node0 = %+v", p.Nodes[0])
	}
	if len(p.Nodes[1].DependsOn) != 1 || p.Nodes[1].DependsOn[0] != "run-1:n1" {
		t.Errorf("node1 deps = %+v", p.Nodes[1].DependsOn)
	}
}

// TestLLMPlanner_StripsMarkdownFence Stub 返回带 ```json 围栏的 JSON，应仍能解析。
func TestLLMPlanner_StripsMarkdownFence(t *testing.T) {
	wrapped := "```json\n" + `{"nodes":[{"id":"x","type":"LLM","name":"gen","input":"hi","dependsOn":[]}]}` + "\n```"
	stub := &llm.Stub{Responder: func(_ llm.Request) string { return wrapped }}
	p, err := (&LLMPlanner{LLM: stub}).Plan(context.Background(), &model.Run{ID: "r", Input: "g"})
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if len(p.Nodes) != 1 || p.Nodes[0].ID != "r:x" {
		t.Errorf("unexpected plan: %+v", p)
	}
}

