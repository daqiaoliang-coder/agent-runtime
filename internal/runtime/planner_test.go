// TestLLMPlanner_MissingID_AutoGenerated 缺省 ID 的节点应自动生成兜底 ID。
func TestLLMPlanner_MissingID_AutoGenerated(t *testing.T) {
	stub := &llm.Stub{Responder: func(_ llm.Request) string {
		return `{"nodes":[{"type":"LLM","name":"gen","input":"hi","dependsOn":[]}]}`
	}}
	p, err := (&LLMPlanner{LLM: stub}).Plan(context.Background(), &model.Run{ID: "run-9", Input: "g"})
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if p.Nodes[0].ID == "" {
		t.Error("expected auto-generated ID for missing id")
	}
	if !strings.HasPrefix(p.Nodes[0].ID, "run-9:") {
		t.Errorf("auto ID should be prefixed by run id, got %q", p.Nodes[0].ID)
	}
}

